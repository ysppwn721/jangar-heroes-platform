const { launch } = require('./browser.cjs');
const assert=require('node:assert/strict');
const fs=require('node:fs');
fs.mkdirSync('test-results',{recursive:true});
const baseURL=process.env.TEST_URL || 'http://127.0.0.1:4173';
const uiOnly=process.env.UI_ONLY === '1';
(async()=>{
 const browser=await launch();
 const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(baseURL,{waitUntil:'networkidle'});
 assert.equal(await page.locator('.hero-card').count(),12);
 if(!uiOnly) await page.locator('#model-viewer.is-ready').waitFor({state:'visible',timeout:30000});
 assert.equal(await page.locator('#model-poster').evaluate(i=>i.complete&&i.naturalWidth>0),true);
 await page.screenshot({path:'test-results/desktop-hero.png'});
 await page.locator('[data-filter="hidden"]').click();assert.equal(await page.locator('.hero-card').count(),2);
 await page.locator('.save-button').first().click();
 await page.locator('[data-filter="saved"]').click();assert.equal(await page.locator('.hero-card').count(),1);
 await page.reload();await page.locator('[data-filter="saved"]').click();assert.equal(await page.locator('.hero-card').count(),1);
 await page.locator('.card-open').click();await page.locator('#hero-dialog').waitFor({state:'visible'});
 assert.equal(await page.locator('#dialog-name').innerText(),'江格尔');
 await page.keyboard.press('Escape');assert.equal(await page.locator('#hero-dialog').isVisible(),false);
 await page.locator('[data-filter="all"]').click();
 await page.locator('[data-hero="4"] .card-arrow').click();
 assert.equal(await page.locator('#model-name').innerText(),'洪古尔');
 if(!uiOnly) await page.locator('#model-viewer.is-ready').waitFor({state:'visible',timeout:30000});
 await page.locator('#expand-view').click();assert.equal(await page.locator('.exhibit.expanded').count(),1);
 assert.equal(await page.locator('.site-header').evaluate(e=>e.inert),true);
 await page.keyboard.press('Escape');assert.equal(await page.locator('.exhibit.expanded').count(),0);
 assert.equal(await page.locator('[inert]').count(),0);
 await page.locator('#random-hero').click();assert.equal(await page.locator('#hero-dialog').isVisible(),true);await page.keyboard.press('Escape');
 for(let y=0;y<await page.evaluate(()=>document.body.scrollHeight);y+=650){await page.evaluate(y=>window.scrollTo(0,y),y);await page.waitForTimeout(80);}
 await page.waitForTimeout(300);await page.screenshot({path:'test-results/desktop-full.png',fullPage:true});
 const broken=await page.locator('img[src]').evaluateAll(imgs=>imgs.filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src));assert.deepEqual(broken,[]);
 await page.setViewportSize({width:390,height:844});await page.goto((process.env.SUBPATH_TEST_URL || baseURL),{waitUntil:'networkidle'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'mobile horizontal overflow');
 await page.locator('.menu-button').click();assert.equal(await page.locator('#navigation').isVisible(),true);
 await page.locator('#navigation a[href="#heroes"]').click();assert.equal(await page.locator('.menu-button').getAttribute('aria-expanded'),'false');
 await page.locator('.card-open').first().click();await page.locator('#dialog-view').click();
 await page.waitForTimeout(700);await page.screenshot({path:'test-results/mobile.png',fullPage:true});
 await page.evaluate(()=>scrollTo(0,0));await page.screenshot({path:'test-results/mobile-top.png'});
 assert.deepEqual(errors,[],'Uncaught browser errors');
 console.log(JSON.stringify({passed:['12 hero cards','first poster decoded','special collection filter','saved filter','saved state after reload','hero details','Escape closes dialog','correct selected hero','expanded viewer and inert cleanup','random encounter','all images loaded','390px no horizontal overflow','mobile menu','repository subpath','zero uncaught errors'],threeD:uiOnly ? 'NOT TESTED: UI_ONLY=1' : 'Initial model and hero switch ready'},null,2));
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
